function randomDemo()
{
	const contents: BoardContents = { width: 19, height: 19, stones: {} };
	if (Math.random() < 0.5)
	{
		if (Math.random() < 0.5)
		{
			if (Math.random() < 0.5)
			{
				contents.width = 9;
				contents.height = 9;
			}
			else
			{
				contents.width = 13;
				contents.height = 13;
			}
		}
		else
		{
			contents.width = Math.floor(Math.random() * 30) + 1;
			contents.height = Math.floor(Math.random() * 30) + 1;
		}
	}
	if (Math.random() < 0.5)
		contents.stones.black = [];
	if (Math.random() < 0.5)
		contents.stones.white = [];
	if (Math.random() < 0.1)
		contents.stones.red = [];
	if (Math.random() < 0.1)
		contents.stones.green = [];
	if (Math.random() < 0.1)
		contents.stones.blue = [];
	if (Math.random() < 0.1)
		contents.stones.yellow = [];
	if (Math.random() < 0.5)
		contents.labels = [];
	const stones = new Set();
	const collections = Object.values(contents.stones);
	const symbols = ["circle", "cross", "square", "triangle"];
	const coordLocations = ["all", "none", "top-left", "bottom-left", "top-right", "bottom-right"] as const;
	for (let y = 0; y < contents.height; y++)
	{
		for (let x = 0; x < contents.width; x++)
		{
			if (collections.length > 0 && Math.random() < 0.25)
			{
				const collection = collections[Math.floor(Math.random() * collections.length)];
				collection.push([x, y]);
				stones.add(`${x},${y}`);
			}
			if (contents.labels && Math.random() < 0.1)
			{
				const label = Math.random() < 0.5
					? (Math.random() < 0.5
						? String.fromCharCode(65 + Math.floor(Math.random() * 26))
						: String(Math.floor(Math.random() ** 2 * 99 + 1)))
					: symbols[Math.floor(Math.random() * symbols.length)];
				contents.labels.push([[x, y], label]);
			}
		}
	}
	if (Math.random() < 0.5)
	{
		contents.policy = Array(contents.width * contents.height).fill(0);
		let max = 1;
		for (let i = 0; i < contents.policy.length; i++)
		{
			const index = Math.floor(Math.random() * contents.policy.length);
			const x = index % contents.width;
			const y = Math.floor(index / contents.width);
			if (contents.policy[index] === 0 && !stones.has(`${x},${y}`))
			{
				contents.policy[index] = Math.random() ** 2 * max;
				max -= contents.policy[index];
			}
		}
		if (Math.random() < 0.5)
		{
			contents.policyQuality = Array.from({ length: contents.policy.length }, () =>
				(Math.random() * 3 - 1.5) * Math.random());
		}
	}
	if (Math.random() < 0.5)
	{
		const moves = new Map();
		while (moves.size <= Math.random() * contents.width * contents.height)
		{
			const x = Math.floor(Math.random() * contents.width);
			const y = Math.floor(Math.random() * contents.height);
			if (!stones.has(`${x},${y}`) && !moves.has(`${x},${y}`))
			{
				moves.set(`${x},${y}`, {
					move: [x, y],
					order: 0,
					playSelectionValue: Math.exp(Math.random() * 30),
					winrate: Math.random(),
					scoreLead: (Math.random() - 0.5) ** 4 * 361,
					visits: Math.floor(Math.exp(Math.random() * 30)),
				});
			}
		}
		contents.moves = [...moves.values()];
		contents.moves.sort((a, b) => b.playSelectionValue - a.playSelectionValue);
		contents.moves.forEach((move, index) => move.order = index);
	}

	const style: Partial<BoardStyle> = {};
	if (Math.random() < 0.5)
		style.backgroundColour = randomColour();
	if (Math.random() < 0.5)
		style.woodColour = Math.random() < 0.5 ? randomColour() : null;
	if (Math.random() < 0.5)
		style.woodScale = Math.tan(Math.random() * Math.PI * 0.5) + 1;
	if (Math.random() < 0.5)
		style.lineColour = randomColour();
	if (Math.random() < 0.5)
	{
		style.starPoints = [];
		const num = Math.floor(Math.random() * 10);
		for (let i = 0; i < num; i++)
		{
			style.starPoints.push([
				Math.floor(Math.random() * contents.width),
				Math.floor(Math.random() * contents.height),
			]);
		}
	}
	if (Math.random() < 0.5)
		style.margin = Math.max(0, Math.min(1, Math.random() * 1.5 - 0.25));
	if (Math.random() < 0.5)
		style.coords = "kanji";
	style.coordsLocation = coordLocations[Math.floor(Math.random() * coordLocations.length)];
	if (Math.random() < 0.1)
		style.fontFamily = "Comic Sans MS";

	drawBoard(canvas, contents, style);

	function randomColour()
	{
		return `#${Math.floor(Math.random() * 0x1000000).toString(16).padStart(6, "0")}`;
	}
}
